// Run against an isolated dev workspace named twill-qa-notes containing qa-tabs.md.
// TWILL_QA_URL=http://127.0.0.1:5178 npm run test:ai-workspace
const {app,BrowserWindow}=require('electron')
const fs=require('node:fs')
app.whenReady().then(async()=>{
 let failed=false
 const w=new BrowserWindow({show:false,width:1500,height:1000,webPreferences:{contextIsolation:true,nodeIntegration:false}})
 try {
  await w.loadURL(process.env.TWILL_QA_URL || 'http://127.0.0.1:5178')
  const result=await w.webContents.executeJavaScript(String.raw`(async()=>{
   const sourceUrl=(path)=>performance.getEntriesByType('resource').find(e=>new URL(e.name).pathname===path)?.name??path
   const {useAppStore,SYSTEM_AI_TAB}=await import(sourceUrl('/src/store.ts'))
   const {useAiStore}=await import(sourceUrl('/src/aiStore.ts'))
   const {api}=await import('/src/api.ts')
   const workspace=await api.workspace()
   if(!workspace.root.endsWith('/twill-qa-notes')) throw new Error('Use an isolated twill-qa-notes workspace')
   const {notifyAiEngineChanged}=await import('/src/aiMaintenance.ts')
   const pause=()=>new Promise(r=>setTimeout(r,350))
   const assert=(v,m)=>{if(!v)throw new Error(m)}
   api.ai.status=async()=>({engine_id:'test',installed:true,logged_in:true,version:'test'})
   api.ai.models=async()=>({models:[]})
   api.ai.usageLimits=async()=>({available:false,blocked:false})
   notifyAiEngineChanged()
   useAppStore.setState({openTabs:[],currentPath:null,view:'editor'})
   await pause()
   useAppStore.getState().openFile('qa-tabs.md')
   useAppStore.getState().moveAi('right')
   await pause()
   const input=document.querySelector('[data-ai-panel-host] textarea')
   assert(input,'chat input missing')
   Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(input,'유지할 한글 초안')
   input.dispatchEvent(new Event('input',{bubbles:true}))
   await pause()
   const drag=async(source,target,zone)=>{
     assert(source,'drag source missing for '+zone+'; tabs='+panes().map(p=>p.textContent.slice(0,100)).join('|'))
     assert(target,'drag target missing for '+zone)
     const transfer=new DataTransfer()
     source.dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:transfer}))
     const rect=target.getBoundingClientRect()
     const clientX=zone==='left'?rect.left+10:zone==='right'?rect.right-10:rect.left+rect.width/2
     const clientY=zone==='top'?rect.top+50:zone==='bottom'?rect.bottom-10:rect.top+rect.height/2
     target.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer:transfer,clientX,clientY}))
     await pause()
     const preview=target.textContent.includes(({left:'왼쪽으로 분할',right:'오른쪽으로 분할',top:'위쪽으로 분할',bottom:'아래쪽으로 분할',center:'이 패널로 이동'})[zone])
     target.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:transfer,clientX,clientY}))
     await pause()
     return preview
   }
   const aiTab=()=>document.querySelector('[data-document-tab-id="system:ai"]')
   const docTab=()=>document.querySelector('[data-document-tab-id="file:qa-tabs.md"]')
   const panes=()=>[...document.querySelectorAll('[aria-label="편집 패널"]')]
   const guide=await drag(document.querySelector('#right-tool-panel [draggable="true"]'),panes()[0],'left')
   assert(guide,'AI edge preview missing')
   assert(panes().length===2,'AI and markdown not split')
   assert(aiTab().getBoundingClientRect().left<docTab().getBoundingClientRect().left,'AI must be left of markdown')
   assert(input===document.querySelector('[data-ai-panel-host] textarea')&&input.value==='유지할 한글 초안','draft lost on docking')
   assert(!document.querySelector('select[aria-label="AI 채팅 위치"]'),'old dropdown remains')
   const bodyTransfer=new DataTransfer()
   docTab().dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:bodyTransfer}))
   const aiPane=aiTab().closest('section'), bodyRect=aiPane.getBoundingClientRect()
   input.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer:bodyTransfer,clientX:bodyRect.right-10,clientY:bodyRect.top+bodyRect.height/2}))
   await pause()
   assert(aiPane.textContent.includes('오른쪽으로 분할'),'drop preview over portal chat body missing')
   input.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:bodyTransfer,clientX:bodyRect.right-10,clientY:bodyRect.top+bodyRect.height/2}))
   await pause()
   assert(panes().length===2&&docTab().getBoundingClientRect().left>aiTab().getBoundingClientRect().left,'markdown drop on AI body failed')
   await drag(aiTab(),docTab().closest('section'),'right')
   assert(panes().length===2&&aiTab().getBoundingClientRect().left>docTab().getBoundingClientRect().left,'move right failed')
   await drag(aiTab(),docTab().closest('section'),'bottom')
   assert(aiTab().getBoundingClientRect().top>docTab().getBoundingClientRect().top,'move bottom failed')
   await drag(aiTab(),docTab().closest('section'),'center')
   assert(panes().length===1,'merge into tab group failed')
   docTab().querySelector('button').click(); await pause()
   assert(input.value==='유지할 한글 초안','draft lost behind document tab')
   aiTab().querySelector('button').click(); await pause()
   await drag(aiTab(),docTab().closest('section'),'left')
   useAppStore.getState().setView('calendar'); await pause()
   const aiReturn=[...document.querySelectorAll('main > div:first-child button')].find(b=>b.textContent.includes('Twill AI'))
   assert(aiReturn,'AI tab missing above calendar')
   aiReturn.click(); await pause()
   assert(panes().length===2&&input.isConnected,'layout lost after calendar')
   const transfer=new DataTransfer()
   aiTab().dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:transfer}))
   const rail=document.querySelector('[aria-label="우측 도구"]')
   rail.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer:transfer}))
   await pause()
   assert(rail.parentElement.textContent.includes('여기에 AI 배치'),'dock preview missing')
   rail.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:transfer}))
   await pause()
   assert(useAppStore.getState().aiLocation==='right'&&panes().length===1,'return to dock failed')
   assert(input===document.querySelector('#right-tool-panel textarea'),'draft remounted on dock return')
   useAppStore.getState().moveAi('editor');await pause()
   aiTab().querySelector('[title="탭 닫기"]').click();await pause()
   assert(useAppStore.getState().view!=='ai'&&!aiTab(),'AI close failed')
   useAppStore.getState().openRightTab(SYSTEM_AI_TAB);await pause()
   assert(aiTab()&&input.value==='유지할 한글 초안','AI reopen failed')

   useAiStore.setState({loadSessions:async()=>{}})
   const base=useAiStore.getState().sessions[0]??{kind:'chat',messages:[],busy:false,queued:false,createdAt:Date.now(),updatedAt:Date.now()}
   const sessions=[{...base,id:'qa-a',title:'프로젝트 A 대화',sectionId:'a',scopeId:'shared'}, {...base,id:'qa-b',title:'프로젝트 B 작업',sectionId:'b',scopeId:'shared'}, {...base,id:'qa-root',title:'미지정 대화',sectionId:null,scopeId:null}]
   useAppStore.setState({sections:[{id:'a',name:'프로젝트 A',scope_id:'shared',expanded:true,items:['qa-tabs.md']},{id:'b',name:'프로젝트 B',scope_id:'shared',expanded:true,items:[]}]})
   let selected=null
   useAiStore.setState({sessions,selectSession:id=>{selected=id;useAiStore.setState({activeSessionId:id})}})
   await pause()
   assert(!document.querySelector('[aria-label="디렉토리별 대화"]'),'global conversation region remains')
   for(const id of ['a','b']){
     const group=document.querySelector('[data-project-ai-tasks="'+id+'"]')
     assert(group&&group.querySelector('[data-ai-session-id="qa-'+id+'"]'),'project group missing '+id)
     assert(group.querySelectorAll('[data-ai-session-id]').length===1,'project sessions mixed')
     assert(group===group.parentElement.lastElementChild,'AI work must be at bottom of project')
   }
   document.querySelector('[data-ai-session-id="qa-b"]').click();await pause()
   assert(selected==='qa-b'&&useAppStore.getState().view==='ai','project session click failed')
   const group=document.querySelector('[data-project-ai-tasks="a"]')
   group.querySelector('button').click();await pause()
   assert(!group.querySelector('[data-ai-session-id]'),'collapse failed')
   group.querySelector('button').click();await pause()
   await drag(aiTab(),docTab().closest('section'),'left')
   return {edgePreview:guide,chatBodyDrop:true,splitDirections:true,tabMerge:true,draftPreserved:true,calendarReturn:true,dockReturn:true,closeReopen:true,projectGrouping:true,projectClick:true}
  })()`)
  console.log(JSON.stringify(result))
  fs.writeFileSync('/tmp/twill-ai-split-qa.png',(await w.webContents.capturePage()).toPNG())
 } catch(e){ console.error(e); fs.writeFileSync('/tmp/twill-ai-split-failed.png',(await w.webContents.capturePage()).toPNG());failed=true } finally {app.exit(failed?1:0)}
})
